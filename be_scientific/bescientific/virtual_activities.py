@dataclass(frozen=True)
class VirtualActivity:
    prompt_en: str
    prompt_hi: str
    choices: tuple[tuple[str, str], ...]
    answer_index: int


def _activity(prompt_en, prompt_hi, choices, answer_index=0):
    return VirtualActivity(prompt_en, prompt_hi, tuple(choices), answer_index)


