ChapterData = tuple[str, str, str, str, str, str, str, str, str, str]


def _course(
    course_id: str,
    id_prefix: str,
    title_en: str,
    title_hi: str,
    book_en: str,
    book_hi: str,
    source_url: str,
    source_url_hi: str | None,
    activity_en: str,
    activity_hi: str,
    chapters: tuple[ChapterData, ...],
) -> StudyCourse:
    lessons = tuple(
        _lesson(
            f"{id_prefix}6-{index:02d}",
            chapter_en,
            chapter_hi,
            (
                focus_en,
                learn_en,
                activity_en.format(focus=focus_en.lower()),
                check_en,
                answer_en,
            ),
            (
                focus_hi,
                learn_hi,
                activity_hi.format(focus=focus_hi),
                check_hi,
                answer_hi,
            ),
        )
        for index, (
            chapter_en, chapter_hi, focus_en, focus_hi,
            learn_en, learn_hi, check_en, answer_en, check_hi, answer_hi,
        ) in enumerate(chapters, 1)
    )
    return StudyCourse(
        course_id, title_en, title_hi, book_en, book_hi,
        source_url, lessons, source_url_hi,
    )


